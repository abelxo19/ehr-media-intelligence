"""Write docs/summary_review.md: the per-patient record of my manual summary review.

    python scripts/review_summaries.py

The numbers (words, diagnoses, grounding, citations) are computed from the current code
and data, so the table cannot drift from the repository. The reviewer notes are mine,
written after reading each summary against its source records.
"""

from __future__ import annotations

import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from app.fhir.mapper import build_all_bundles  # noqa: E402
from app.ingestion.pipeline import run_ingestion  # noqa: E402
from app.summarization.prompt import MAX_SUMMARY_WORDS, render_bundle  # noqa: E402
from app.summarization.summarizer import RuleBasedSummarizer, check_grounding, count_words  # noqa: E402

TODAY = date(2026, 11, 20)
OUT = ROOT / "docs" / "summary_review.md"

# patient_id -> (verdict, note). "fixed" = an issue I found and fixed, with the guarding test.
REVIEW_NOTES: dict[str, tuple[str, str]] = {
    "pt-0012345": ("ok", "DM2 + CKD + AKI + retinopathy all present; eGFR 27 and HbA1c 10.8 flagged."),
    "pt-0023456": ("fixed", "Note said \"52-year-old\" but DOB gives 53 on 2026-05-18. Data corrected; "
                            "guarded by `test_ages_stated_in_notes_match_date_of_birth`."),
    "pt-0034567": ("ok", "Asthma exacerbation; eosinophils 8.5% flagged."),
    "pt-0045678": ("ok", "HFrEF; duplicate-MRN identity flag listed first among anomalies."),
    "pt-0056789": ("ok", "Short (single problem); normal MRI correctly not flagged."),
    "pt-0067890": ("limitation", "Chief concern reads \"COPD GOLD 2\" (latest progress note) although the "
                                 "clinically dominant issue is the suspected lung malignancy, which *is* listed "
                                 "under media and anomalies. Rules can't rank clinical priority; not fixed in "
                                 "the fallback, left to the LLM + clinician review."),
    "pt-0078901": ("ok", "Appendicitis; CT finding and WBC 16.4 / neutrophils 86% flagged."),
    "pt-0089012": ("ok", "Critical K 6.3 listed first; renal artery stenosis captured."),
    "pt-0099012": ("fixed", "Mammogram finding was its first sentence, \"Diagnostic mammogram, left breast.\" "
                            "Now selects the BI-RADS 4C sentence; guarded by "
                            "`test_mammogram_finding_uses_the_significant_sentence`."),
    "pt-0101123": ("gap", "Stroke and carotid stenosis captured, but the later carotid endarterectomy "
                          "(operative note) is not mentioned: the fallback only draws notes into the chief "
                          "concern. Also repeats \"MRI Brain: MRI brain\" in one anomaly. Left to the LLM."),
    "pt-0112234": ("ok", "Hypothyroidism, osteoporosis, vitamin D deficiency captured."),
    "pt-0123345": ("ok", "Scaphoid fracture; normal creatinine correctly not flagged."),
}


def main() -> None:
    dataset = run_ingestion(ROOT / "data" / "raw", today=TODAY)
    bundles = build_all_bundles(dataset)
    names = {p.patient_id: p.display_name for p in dataset.patients}
    rows, words_all, dx_all = [], [], []
    for pid in sorted(bundles):
        rendered, ids = render_bundle(bundles[pid], today=TODAY)
        content = RuleBasedSummarizer().generate(rendered, bundles[pid])
        report = check_grounding(content, rendered, ids)
        words, dx = count_words(content), len(content.key_diagnoses)
        words_all.append(words)
        dx_all.append(dx)
        verdict, note = REVIEW_NOTES.get(pid, ("-", "not reviewed"))
        rows.append(f"| {names[pid]} (`{pid}`) | {words} | {dx} | {report.score:.0%} | "
                    f"{len(report.invalid_citations)} | {verdict} | {note} |")

    lines = [
        "# Summary review record",
        "",
        f"Generated by `scripts/review_summaries.py` with `{RuleBasedSummarizer.name}` "
        f"(the summarizer that produced the shipped summaries; see *Claude run* below).",
        "",
        f"- Patients: {len(rows)}; words {min(words_all)}-{max(words_all)} (limit {MAX_SUMMARY_WORDS}); "
        f"diagnoses per summary {min(dx_all)}-{max(dx_all)}",
        "- Grounding = share of diagnoses / findings / anomalies whose numbers and key words appear in the "
        "source records; invalid = cited record ids that don't exist.",
        "",
        "| Patient | Words | Dx | Grounding | Invalid ids | Verdict | Reviewer note |",
        "|---|---|---|---|---|---|---|",
        *rows,
        "",
        "## Claude run",
        "",
        "On 2026-11-20 I ran `python -m app.pipeline --summarizer claude`. The API key authenticated, but every "
        "request returned HTTP 400 *\"Your credit balance is too low to access the Anthropic API\"*, so all 12 "
        "patients fell back to the rule-based summarizer as designed (run stats: `fallbacks: 12`, "
        "`by_generator: {rule-based:v2: 12}`). The Claude request and error handling are covered by mocked tests "
        "in `tests/test_summarizer.py`; Claude output itself has not been reviewed yet.",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUT}")


if __name__ == "__main__":
    main()
